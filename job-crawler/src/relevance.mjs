/** 判定标题是否与用户研发目标相关。技术词优先,再判无关词,都不含默认放行。 */
export function isRelevantJob(title) {
  if (!title) return false;
  const lc = String(title).toLowerCase();
  if (TECH_KW.some((k) => lc.includes(k))) return true;
  if (IRREL_KW.some((k) => lc.includes(k))) return false;
  return true;
}

